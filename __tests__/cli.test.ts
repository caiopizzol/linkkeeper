function registry(links: Record<string, { path: string; repository?: string; ref?: string }>): Routes {
  const body = JSON.stringify({ version: 1, defaults: { repository: 'acme/site', ref: 'main' }, links });
  return { [`GET ${REGISTRY_URL}`]: ok(body) };
}


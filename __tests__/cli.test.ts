function readTree(root: string): Record<string, string> {
  const files: Record<string, string> = {};
  for (const relative of readdirSync(root, { recursive: true, encoding: 'utf8' })) {
    const full = path.join(root, relative);
    if (statSync(full).isFile()) files[relative.split(path.sep).join('/')] = readFileSync(full, 'utf8');
  }
  return files;
}

function run({ args, inputs, routes }: Case) {
  const cwd = mkdtempSync(path.join(tmpdir(), 'linkkeeper-cwd-'));
  const fake = mkdtempSync(path.join(tmpdir(), 'linkkeeper-fake-'));
  try {
    for (const [relative, text] of Object.entries(inputs)) {
      mkdirSync(path.dirname(path.join(cwd, relative)), { recursive: true });
      writeFileSync(path.join(cwd, relative), text);
    }
    const log = path.join(fake, 'requests.jsonl');
    writeFileSync(path.join(fake, 'routes.json'), JSON.stringify(routes));
    writeFileSync(log, '');

    const result = spawnSync(process.execPath, ['--no-env-file', '--preload', FAKE_FETCH, CLI, ...args], {
      cwd,
      encoding: 'utf8',
      env: {
        HOME: process.env.HOME,
        GITHUB_TOKEN: SECRET,
        LINKKEEPER_FAKE_ROUTES: path.join(fake, 'routes.json'),
        LINKKEEPER_FAKE_LOG: log,
      },
    });
    const requestLog = readFileSync(log, 'utf8');
    return {
      status: result.status,
      stdout: result.stdout,
      stderr: result.stderr,
      requestLog,
      requests: requestLog
        .split('\n')
        .filter(Boolean)
        .map((line) => JSON.parse(line) as Recorded),
      tree: readTree(cwd),
    };
  } finally {
    rmSync(cwd, { recursive: true, force: true });
    rmSync(fake, { recursive: true, force: true });
  }
}

describe('linkkeeper CLI', () => {
  test('every declared command and flag has a case', () => {
    const declared = Object.entries(COMMANDS).flatMap(([command, flags]) => [
      command,
      ...flags.map((name) => `${command} --${name}`),
    ]);
    const exercised = new Set(
      Object.values(cases).flatMap(({ args: [command = '', ...rest] }) => [
        command,
        ...rest.filter((arg) => arg.startsWith('--')).map((arg) => `${command} ${arg}`),
      ]),
    );
    expect(declared.filter((surface) => !exercised.has(surface))).toEqual([]);
  });

  test.each(Object.entries(cases))('%s', (_name, expected) => {
    const actual = run(expected);

    for (const output of [actual.stdout, actual.stderr, actual.requestLog, ...Object.values(actual.tree)]) {
      expect(output).not.toContain(SECRET);
    }
    expect(actual.stderr).toBe(expected.stderr);
    expect(actual.stdout).toBe(expected.stdout);
    expect(actual.status).toBe(expected.status);
    expect(actual.requests).toEqual(expected.requests);
    expect(actual.tree).toEqual({ ...expected.inputs, ...expected.written });
  });
});
